"""Optional module: organised force.

THE RULE IN PLAIN WORDS

The nine modules cannot tell a war from an ordinary bout of stagflation. This module adds the
difference. It holds one number, the level of organised force, between 0 and 1. Nothing sets
that number from outside. It follows the depth regime that dominant capital itself produces.

  1. The call for force. The call for force in a year is the intensity of stagflation. If the
     coalitions module is on, the call is the intensity of stagflation or that module's level
     of conflict, whichever is higher.
  2. The level of force. While the call is above the level, the level closes one third of the
     gap each year, because arms contracts take about three years to become deliveries. While
     the call is below the level, the level closes a smaller part of the gap each year,
     because an apparatus of force outlasts the conflict that built it.
  3. The arms contractors. The contractors are the firms of the top hundred that sit in the
     arms sectors. If the coalitions module is on, the contractors are the firms of the top
     hundred that carry its conflict label. No other firm receives a military order.
  4. Military orders. At full force, government organs spend a fixed part of all income on
     the military, and a fixed part of that spending goes to the contractors. The module
     turns that spending into a number of jobs on the contractors' books, as the same part
     of the working population. Each year the module plans the hiring or the dismissals that
     would bring those jobs to the number the level of force calls for. It publishes the plan.
     The contractors carry out the plan in the following year. Planned hiring is limited to a
     part of the people who are out of work. The contractors keep their markup while they
     grow, because military orders are not won by cutting prices.
  5. Room for the hiring. The green-field module sets the planned military hiring aside
     before it lets other firms hire, so that employment cannot pass the working population.
  6. Repression. Organised force wears down popular resistance. The module publishes a
     yearly rate, in proportion to the level of force, and the resistance module removes that
     part of the level of popular resistance each year.
  7. Readouts. The module publishes the level of force, the military jobs as a part of the
     working population, and the contractors' part of the top hundred's capitalization.

Force therefore does three things that an ordinary bout of stagflation does not do. It enlarges
the arms contractors at the expense of every other firm, in the differential sense. It puts
people to work while prices rise. It holds down the resistance that inflation provokes. The
module gives force two costs, and both arise in other modules. Lower unemployment lets wages
gain on prices in the sabotage module. Lower unemployment also loosens the concert of dominant
capital in the compass, which limits the intensity of stagflation.

WHAT IT RESTS ON

  - Capital as Power, chapter 12, "The differential underpinnings of universal sabotage". The
    means of differential profit include "the use of force, including military, for
    differential business ends". A footnote to the same chapter: "US military contractors,
    engaged in the most destructive form of business enterprise, sometime operate at as
    little as 10 per cent of their capacity - while earning superior rates of return".
  - Chapter 13. "war and organized violence - nominally the archenemies of the 'free market'
    - had been absorbed into capital", and "the government bond represents a share in the
    organized violence of society". Force is therefore not an outside event in this theory.
  - Chapter 16, "The stagflation norm". Buyers pay higher prices because "they are forced.
    And the way to force them is by creating, imposing and maintaining various forms of
    social crisis, apparent or real. Military hostilities during the First World War" head the
    list of examples. Such crises "undermine the ability of most people to resist price
    increases". "Unemployment and stagnating production, along with other forms of
    instability, conflict and force, constitute the necessary backdrop for differential
    accumulation through differential inflation." Parts 1 and 6 rest on this.
  - Chapter 17, "Amalgamation versus stagflation". In depth, "sustaining such
    accumulation-through-crisis requires entrenchment, fortified power arrangements and a
    greater use of force and violence". "The new depth regime" of the 1930s "was marked by
    the massive use of military force", and the depth regime of the 1970s "was accompanied by
    heightened conflict and violence". Part 1 rests on these sentences.
  - Chapter 17, "The role of the Middle East", with Figure 17.2. The chart "shows a positive
    long-term correlation between inflation in the industrialized countries on the one hand
    and the global arms trade expressed as a share of world GDP on the other", which "points
    to the conflictural underpinnings" of the regimes. Arms exports are "a handy proxy for
    'bellicosity'". A footnote says that "military contracts ... lead deliveries roughly by
    three years". The lag in part 2 is this figure.
  - Nitzan and Bichler, "Bringing Capital Accumulation Back In" (1995), section 2. From 1966
    to 1991 "the largest 100 contractors accounted for between 62 and 72 per cent" of all
    prime contract awards. The share of sixteen large contractors in the net profit of the
    Fortune 500 rose from 3.8 per cent in 1974 to 10.7 per cent in 1985 as "defence budgets"
    rose, and "this persistent military bias served to enhance the relative power of the
    Arma-Core". The paper reports Kalecki's prediction that a rise in military budgets "would
    bring a redistribution of income from the old to the new groups". It adds that "military
    expenditures must be legitimized by external threats", so that "domestic weapon
    procurement is inherently unstable". The arms sellers "succeeded in avoiding price
    competition". Parts 3 and 4 rest on this.
  - Nitzan and Bichler, The Global Political Economy of Israel (2002), chapter 5, reporting
    Kalecki. Military spending "might have lessened the disciplinary impact of unemployment",
    but "the 'shortfall' was more than compensated for by the direct use of force and
    violence in the name national security". In Kalecki's fascist model "full employment was
    sustained by military spending in preparation for war". Parts 4 and 6 rest on this.
  - Bichler and Nitzan, "Dominant Capital and the New Wars" (2004). Figure 16 gives United
    States military spending as a part of gross domestic product: 15 per cent in the First
    World War, 43 per cent in the Second, 15 per cent in the Korean war, 10 per cent in the
    Vietnam war, 7.5 per cent under Reagan and 3.8 per cent in 2000. The conflict coalition
    "needs an atmosphere of permanent threat". The contractors' "differential profits are
    likely to rise - partly from rising sales to the region, but mostly from increased
    spending at home". The paper says that war needed "dominant capital on board", and that
    this condition was met when "the collective mindset of dominant capital has finally
    started to shift from breadth to depth". Part 1 follows this order of events.

WHAT IS ADDED

The literature gives directions, three figures and no rule. The three figures are the lag of
three years, the part of contracts that the hundred largest contractors receive, and the part
of income spent on the military in past wars. Every other number is an addition. Reckoning
military spending as jobs on the contractors' books is an addition, made because the ledger
counts employees and holds no account of sales. Setting the call for force equal to the
intensity of stagflation is an addition in its form. The speed at which force fades, the limit
on yearly hiring and the rate of repression are additions. The choice of arms sectors is an
addition, and it copies the sectors that the coalitions module gives to its conflict coalition.

WHAT IS MISSING

The module does not say who pays for the orders. In the literature the government pays by
taxing broadly and by selling bonds to large owners, and the ledger has no taxes. Soldiers are
not counted, so the armed forces take nobody out of the working population. Arms exports, the
buyers of arms abroad and the destruction of war are not in the ledger. The module raises no
price. The price rise of a conflict belongs to the stagflation module and to the coalitions
module. Nitzan and Bichler, "New Imperialism or New Capitalism?" (2006), say that war is
"detrimental to capital mobility, the lifeline of global breadth", and this module does not
close any boundary. The module holds no resistance
to war itself.
"""
import numpy as np
from core import Scale, Publish, top_positions

CONFLICT_LABEL, UNSET_LABEL = 1, -1     # the codes the coalitions module uses for its labels


class Force:
    name = "force"
    reads = ("stagflation_intensity",)
    supplies = ("force", "repression", "force_hires", "force_jobs", "force_contractors_top")

    def __init__(self, arms_sectors=(0, 1), lag=3.0, fade=0.15, military_part=0.15, top_part=0.67,
                 take=0.5, repress=0.15, hold=0.1, floor=0.005, top=100):
        self.arms_sectors = arms_sectors    # sectors whose firms can be arms contractors (the conflict sectors of the coalitions module)
        self.lag = lag                      # years from contract to delivery: the level of force closes one part in this many of a gap each year (chapter 17, footnote)
        self.fade = fade                    # part of the gap closed each year while the call for force is below the level
        self.military_part = military_part  # military spending as a part of all income at full force. The value is an addition: 15 per cent is the reading for the First World War and for Korea in one chart of United States spending, in which the Second World War reads 43 per cent, and the literature does not give it as the level that full force brings
        self.top_part = top_part            # part of military orders that goes to the contractors of the top hundred. The value is an addition: 62 to 72 per cent is the part of prime contract awards that the hundred largest military contractors received from 1966 to 1991, which is a different group from the arms firms among the hundred largest firms, and 0.67 is the middle of that range
        self.take = take                    # the most that one year's military hiring may take of the people out of work
        self.repress = repress              # part of popular resistance removed in a year at full force
        self.hold = hold                    # smallest part of its employees a contractor keeps in a year of dismissals
        self.floor = floor                  # unemployment cannot fall below this (the same figure as in the green-field module)
        self.top = top
        self.level = 0.0                    # the level of organised force, from 0 to 1
        self.jobs = 0.0                     # military jobs now on the contractors' books
        self.planned = 0.0                  # hiring (+) or dismissals (-) planned last year for this year

    def contractors(self, L):
        """Positions of the arms contractors, and the top hundred."""
        top = top_positions(L.cap(), np.arange(len(L)), self.top)
        in_arms = np.isin(L.sector[top], list(self.arms_sectors))
        label = L.extra.get("coalition")            # the labels of the coalitions module, if it is on
        if label is not None:
            lab = label[top]
            in_arms = (lab == CONFLICT_LABEL) | ((lab == UNSET_LABEL) & in_arms)
        return top[in_arms], top

    def readouts(self, L):
        mine, top = self.contractors(L)
        K = L.cap()
        return [Publish("force", self.level, self.name),
                Publish("repression", self.repress * self.level, self.name),
                Publish("force_hires", max(self.planned, 0.0), self.name),
                Publish("force_jobs", self.jobs / L.shared["workforce"], self.name),
                Publish("force_contractors_top", float(K[mine].sum() / K[top].sum()), self.name)]

    def start(self, L):
        return {c.key: c.value for c in self.readouts(L)}

    def propose(self, L, rng):
        A = L.accounts
        mine, top = self.contractors(L)
        employed, held = L.n.sum(), L.n[mine].sum()
        changes = []

        # Part 4, second half: the contractors carry out the plan published last year.
        done = 0.0
        if mine.size and self.planned > 0:
            workforce = L.shared["workforce"] * (1 + L.shared["workforce_growth"])
            done = min(self.planned, max(workforce * (1 - self.floor) - employed, 0.0))
        elif mine.size and self.planned < 0:
            done = -min(-self.planned, self.jobs, (1 - self.hold) * held)
        if done != 0.0:
            factor = np.ones(len(L))
            factor[mine] = 1 + done / held          # each contractor in proportion to its size
            changes.append(Scale("employees", factor, self.name))
        self.jobs += done

        # Parts 1 and 2: the call for force and the level of force.
        call = float(np.clip(max(A.get("stagflation_intensity", 0.0), A.get("conflict", 0.0)), 0.0, 1.0))
        gap = call - self.level
        self.level = float(np.clip(self.level + gap * (1 / self.lag if gap > 0 else self.fade), 0.0, 1.0))

        # Part 4, first half: the plan for next year.
        workforce = L.shared["workforce"]
        wanted = self.military_part * self.top_part * self.level * workforce - self.jobs
        if wanted > 0:
            idle = workforce * (1 - self.floor) - (employed + done)
            wanted = min(wanted, self.take * max(idle, 0.0))
        self.planned = float(wanted)
        return changes + self.readouts(L)

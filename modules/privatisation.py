"""Optional module: privatisation.

THE RULE IN PLAIN WORDS

The main modules give dominant capital two ways to add employees: hiring and buying other
firms. This module adds a third. It holds a pool of publicly run employment: people who work
for government organs and for no firm. Dominant capital takes over parts of that pool when it
is able to act in concert, and popular resistance holds the pool shut and adds to it.

  1. The pool. The pool is a number of employees that the module keeps outside the ledger. No
     firm earns anything from them, and they are not part of the working population that the
     ledger counts, which is the population that works for firms or looks for work with them.
     At the start of a run the pool is a fixed part of that working population. Each year the
     pool grows at the rate at which the working population grows.
  2. The door. Each year the module works out how far the door to the pool is open. The door
     is the cohesion of dominant capital, times one minus the defence. The defence is twice
     the level of popular resistance, and never more than 1. With no cohesion the door is
     shut. With popular resistance at one half or above the door is shut.
  3. The takeover. Dominant capital plans to take over, in the following year, a fixed part
     of the pool times the door. The plan is limited to a part of the employees that the
     hundred largest firms already have. The module publishes the plan.
  4. Carrying out the plan. In the following year the planned number of employees leaves the
     pool and goes onto the books of the hundred largest firms, to each in proportion to the
     employees it already has. Each of those firms keeps its earnings per employee and its
     price. The services were not sold before and are sold at a markup afterwards. The
     green-field module adds the same number of people to the working population of the
     ledger, because the people come with their jobs, and it sets the same number aside
     before it lets other firms hire.
  4a. The price. Dominant capital pays for what it takes over, and it pays less than the
     worth. The worth is the capitalization that the takeover adds to the hundred largest
     firms: their capitalization times the employees taken over, divided by the employees
     they had. The price is a set part of the worth. The module publishes the price as the
     proceeds of the year. Module 2 retires government debt with the proceeds in the
     following year. The government then owes less interest, and when the public debt module
     is on, less tax is collected and less interest is paid to the holders of the debt. No
     firm's earnings change: the owners of the buying firms hand over bonds, or money that
     retires bonds, and the ledger counts a firm's debt and equity together. With the part
     set to 0 the services are given away, and with 1 they are sold at their full worth.
  5. No new capacity. The takeover is not counted as growth of capacity in any industry. The
     sabotage module wears markups down where capacity grows faster than the working
     population, and that part of its rule does not see the takeover.
  6. Public hiring under resistance. While popular resistance is above zero, government organs
     plan to hire, in the following year, a part of the people who are out of work. The part
     is a fixed rate times the level of popular resistance. Those people leave the working
     population of the ledger and join the pool.
  7. Readouts. The module publishes the pool as a part of all working people, the door, the
     planned takeover and the planned public hiring as parts of the working population, and
     the part of the top hundred's employees that came from the pool.
  8. Who pays public employees. Each person in the pool is paid the wage. A tax of the same
     year pays for it: one rate on the wage bill of the firms and on every firm's earnings.
     Wage earners and firms pay the tax to the government, and the government pays it out to
     wage earners as the pay of public employees. A firm cannot pay more than it earns. With
     a pool of 5 per cent of the working population, the rate is a little under 5 per cent.
     When dominant capital takes over part of the pool, the tax falls for everybody. The
     module publishes the rate.

Nothing in the rule comes from outside. Cohesion comes from the compass, resistance from the
resistance module, and the pool is filled and emptied only by those two.

WHAT IT RESTS ON

  - Capital as Power, chapter 17, "The role of the Middle East" (the passage on the breadth
    phase that began in the late 1980s). "The ideological demise of public ownership and the
    'mixed economy' opened the door for privatization of state assets and government
    services, which, from the viewpoint of dominant capital, was tantamount to green-field
    investment." "Together, the combination of expansion into less developed countries,
    privatization and corporate amalgamation helped sustain a powerful breadth drive for large
    Western corporations despite the lacklustre growth of their 'parent' countries." Parts 3
    and 4 rest on this: the takeover adds employees to dominant capital, as hiring does.
  - The footnote to that passage. Government expenditures "have risen from 14 per cent of GDP
    in the 1960s to 17 per cent in the 1980s, and remained more or less at that level since
    then". "The privatization of such services - including transportation, water,
    infrastructure, education and security - typically takes the form of giving/selling them
    to dominant capital, which in turn contributes to differential accumulation in a manner
    similar to green-field investment." Part 4 gives the whole takeover to the hundred
    largest firms because of the words "to dominant capital".
  - Bichler and Nitzan, The Global Political Economy of Israel (2002), chapter 6. "The second
    pole was privatisation. Part of this involved the sale of government-owned enterprises,
    but there was a much bigger prize here, namely the privatisation of government itself."
    "Much of this activity could be turned over to private hands; and since these usually
    ended up being the largest firms, the effect was tantamount to boosting differential
    accumulation through external breadth." The same book says that state assets went to
    large donors "at bargain prices", that the group of state-owned firms "functioned more as
    a storage facility for privatisation targets, than as an accumulation-driven
    organisation", and that in privatisation the thing that let "money make money" "was often
    having the right political friends". Part 1 (a pool that earns nothing and waits) and the
    low price of part 4a rest on these sentences. The same chapter says of one sale that the
    buyer "ended up getting it for a song", of another that workers "never saw a cent of the
    proceeds", and of a later plan that the state "would plow some of the privatisation
    proceeds" into a fund. The proceeds therefore go to the government. The literature
    gives no figure for the price.
  - Capital as Power, chapter 9. "Capitalization ... privatized and priced more and more
    social activities." Part 4 lets the services carry a markup once a firm holds them.
  - Chapter 15, "Green-field". Green-field growth "is no panacea for dominant capital",
    because new capacity threatens prices. Chapter 14 defines external breadth as "building
    new capacity and hiring new employees faster than the average". Privatisation hires
    without building. Part 5 rests on that difference, and it is an interpretation.
  - Chapter 4. "Since the 1970s, the public autonomy of the welfare state, limited as it was
    to begin with, has been significantly diminished. Large chunks of the public domain have
    been privatized and handed over to the capitalists", with "little to prevent" it once
    opposition had been neutralised. Chapter 5: "once communism collapsed in the late 1980s,
    government officials and politicians around the world seemed all too eager to dismantle
    their own welfare states". Part 2 rests on these: the door opens when opposition is weak.
  - Chapter 5. "Large governments have become integral if not necessary to the process of
    capital accumulation", and the public sector "remained subservient to ... the interests
    of its large capitalists". Chapter 13 treats corporations and government organs as bodies
    of one mode of power. The pool is therefore not an opponent of dominant capital. It is a
    part of the same order that has not yet been capitalized.
  - Bichler and Nitzan, "Regimes of Differential Accumulation" (2001), conclusion. "The global
    pool of takeover targets - including the privatization of state-owned firms and public
    services - remains vast." Nitzan and Bichler, "New Imperialism or New Capitalism?" (2006):
    "policy practice has increasingly tilted in favor of amalgamation - via deregulation ...,
    privatization, subsidies, and tax incentives".

WHAT IS ADDED

The literature says who receives privatised services, that the receipt works like green-field
growth, and that the door opened when the ideology of public ownership collapsed. It gives no
rule and no rate. Every number below is an addition. The starting pool of 5 per cent is an
addition, and the book's figure of 14 to 17 per cent of gross domestic product is for the
world from the 1960s and is a record to compare with. Measuring the door by cohesion times one
minus twice the resistance is an addition. The yearly part of the pool that can be taken and
the limit on a year's takeover are additions. Giving each of the hundred largest firms a part
in proportion to its employees is an addition. Part 6 is wholly an addition. The literature
says that the welfare state was built after the Great Depression and does not say what built
it. Part 6 gives the pool a source inside the model, and its rate can be set
to zero. Letting the pool grow with the working population is an addition.

Part 8 is an addition. The book says that a government bond capitalizes "the power of
government to tax" (chapter 13), and gives no rule for who pays the tax for public services.
One rate on all income is the rule of the public debt module. That a public employee is paid
the wage of the firms is an addition.

In part 4a, the part of the worth that is paid is a plain setting
with no source. Its default of one half is the middle between giving and selling at full
worth, and nothing more. Using the proceeds to retire debt is an addition.

WHAT IS MISSING

The module does not show the payments that government organs go on making to the firms that
now run the services. Once a service is taken over, the tax for it stops, and the earnings on
privatised employees come from a markup, which whoever buys the services pays in the price,
as with every markup in the model. Public employees pay no tax on their own pay. The
sale of state-owned firms as whole firms is not modelled, only the takeover of employment.
The pool has no industries: privatised employees take the industry of the firm that receives
them. The book places privatisation in a breadth phase, beside mergers, and this rule does not
close the door during stagflation except through the resistance that stagflation provokes.
Privatisation provokes no resistance of its own, which follows the book's remark that the
population is "impartial to breadth", and may be too kind.
"""
import numpy as np
from core import Scale, Publish, Transfer, top_positions, lend_to_government, WAGE_EARNERS, GOVERNMENT

TAX = "tax for public employment"       # this module's income component: what each firm pays, for each employee; the core sets it
TAX_EARNINGS = "tax on earnings for public employment"
TAX_WAGES = "tax on wages for public employment"
PAY = "pay of public employees"
LENT = "lent to the government for public employment"   # below 0 in a year, repaid by it


class Privatisation:
    name = "privatisation"
    reads = ("cohesion", "resistance")
    supplies = ("privatisation_jobs", "public_workforce_change", "public_pool", "privatisation_door",
                "privatisation_rate", "public_hiring_rate", "privatised_part_of_top",
                "privatisation_proceeds", "public_pay_tax")
    figures = {                   # what the workbench calls each published number: label, unit, note
        "privatisation_jobs": ("Public jobs taken over", "number", "Takeover planned for the year, in employees."),
        "public_workforce_change": ("Change in public employment", "number", "Planned takeover less planned public hiring, in employees."),
        "public_pool": ("Public employment", "share", "Publicly run employment as a part of all working people."),
        "privatisation_door": ("Door to privatisation", "index", "Cohesion of the top 100 times one minus the defence."),
        "privatisation_rate": ("Privatisation rate", "rate", "Planned takeover as a part of the working population."),
        "public_hiring_rate": ("Public hiring rate", "rate", "Planned public hiring as a part of the working population."),
        'privatised_part_of_top': ('Top 100 employees from privatisation', 'share', "Part of the top 100's employees that came from the public pool."),
        'privatisation_proceeds': ('Privatisation proceeds', 'number', "What the top 100 paid for the year's takeover, in money."),
        "public_pay_tax": ("Tax for public employment", "share", "The rate charged on wages and on earnings to pay public employees."),
    }

    def __init__(self, start_part=0.05, absorb=0.3, defend=2.0, max_growth=0.25, build=0.1,
                 floor=0.005, price_part=0.5, top=100):
        self.start_part = start_part    # the pool at the start, as a part of the working population that the ledger counts
        self.absorb = absorb            # part of the pool that dominant capital takes over in a year when the door is fully open
        self.defend = defend            # part of the door that is shut per unit of popular resistance
        self.max_growth = max_growth    # the most that one year's takeover may add to the employees of the hundred largest firms, as a part of those employees
        self.build = build              # part of the people out of work that government organs hire in a year at full popular resistance; 0 switches public hiring off
        self.floor = floor              # unemployment cannot fall below this (the same figure as in the green-field module)
        self.price_part = price_part    # part of the worth of a takeover that dominant capital pays to the government; a plain setting with no source: 0 gives the services away, 1 sells them at full worth
        self.top = top
        self.proceeds = 0.0             # what dominant capital paid for this year's takeover, in money
        self.pool = 0.0                 # publicly run employment, in employees
        self.planned_take = 0.0         # takeover planned last year for this year, in employees
        self.planned_build = 0.0        # public hiring planned last year for this year, in employees
        self.taken = 0.0                # employees of the top hundred that came from the pool (grows with the working population)
        self.door = 0.0
        self.rate = 0.0                 # the tax for the pay of public employees, as a part of earnings; set in law once, then moved only as the debt module orders
        self.in_law = False             # whether the rate has been set
        self.wage_rate = 0.0            # the rate on wages: the same as the rate on earnings when set, then moved as the debt module orders

    def readouts(self, L, held):
        W = L.shared["workforce"]
        out = {"privatisation_jobs": self.planned_take,                                  # read by the green-field module
               "public_workforce_change": self.planned_take - self.planned_build,        # read by the green-field module
               "public_pool": self.pool / (self.pool + W),                               # the pool as a part of all working people
               "privatisation_door": self.door,
               "privatisation_rate": self.planned_take / W,
               "public_hiring_rate": self.planned_build / W,
               "privatised_part_of_top": min(1.0, self.taken / held) if held > 0 else 0.0,
               "privatisation_proceeds": self.proceeds,                                  # read by module 2, which retires government debt with it
               "public_pay_tax": self.rate}
        return [Publish(key, float(value), self.name) for key, value in out.items()]

    def start(self, L):
        # What each firm pays in tax for public employment is recorded by the core in this component.
        L.add_component(TAX, self.name, kind="income", transfers=True)
        self.pool = self.start_part * L.shared["workforce"]                              # part 1
        top = top_positions(L.cap(), np.arange(len(L)), self.top)
        return {c.key: c.value for c in self.readouts(L, L.n[top].sum())}

    def propose(self, L, rng):
        A = L.accounts
        W, g = L.shared["workforce"], L.shared["workforce_growth"]
        K = L.cap()
        top = top_positions(K, np.arange(len(L)), self.top)
        employed, held = L.n.sum(), L.n[top].sum()
        changes = []

        # Part 4: carry out the takeover planned and published last year.
        take, built = min(self.planned_take, self.pool), self.planned_build
        if take > 0 and held > 0:
            factor = np.ones(len(L))
            factor[top] = 1 + take / held
            changes.append(Scale("employees", factor, self.name))
        else:
            take = 0.0
        # Part 4a: the price is a part of the capitalization that the takeover adds to the hundred largest firms.
        self.proceeds = float(self.price_part * K[top].sum() * take / held) if held > 0 else 0.0
        self.pool = self.pool * (1 + g) - take + built        # parts 1, 4 and 6
        self.taken = self.taken * (1 + g) + take

        # Part 2: the door.
        resistance = float(np.clip(A["resistance"], 0.0, 1.0))
        cohesion = float(np.clip(A["cohesion"], 0.0, 1.0))
        self.door = cohesion * (1 - min(1.0, self.defend * resistance))

        # Part 3: the plan for next year's takeover.
        self.planned_take = float(min(self.absorb * self.door * self.pool, self.max_growth * held))

        # Part 6: the plan for next year's public hiring, from the people out of work.
        idle = W * (1 - self.floor) - employed - built - A.get("force_hires", 0.0)
        self.planned_build = float(self.build * resistance * max(idle, 0.0))

        # Part 8: the pay of public employees and the tax that pays it. One rate is charged on the
        # wage bill and on each firm's earnings before this tax. The government pays it out as pay.
        wage = L.shared["wage"]
        pay = self.pool * wage
        wages = wage * employed
        base = np.maximum(L.earnings() - L.n * L.components[TAX], 0.0)
        # The rate is set in law in the first year with public pay, to cover that year's pay.
        # The difference between the pay and the tax at that rate is lent by owners, or repays them.
        # Once in law, the rates move as the debt module orders after a surplus or a deficit.
        if self.in_law:
            self.rate *= L.accounts.get("tax_kept_earnings", 1.0)
            self.wage_rate *= L.accounts.get("tax_kept_wages", 1.0)
        if not self.in_law and pay > 0:
            self.rate, self.in_law = float(pay / (wages + base.sum())), True
            self.wage_rate = self.rate
        if self.in_law:
            taxed = (self.rate * base.sum(), self.wage_rate * wages)
            tax = self.rate * (wages + base.sum()) if self.wage_rate == self.rate else sum(taxed)
            changes += [Transfer(TAX_EARNINGS, payer=self.rate * base, receiver=GOVERNMENT, source=self.name),
                        Transfer(TAX_WAGES, payer=WAGE_EARNERS, receiver=GOVERNMENT, source=self.name,
                                 amount=self.wage_rate * wages)]
            changes += lend_to_government(LENT, float(pay - tax), L, GOVERNMENT, self.name, taxed)
            if pay > 0:
                changes.append(Transfer(PAY, payer=GOVERNMENT, receiver=WAGE_EARNERS, source=self.name, amount=pay))
        return changes + self.readouts(L, held + take)

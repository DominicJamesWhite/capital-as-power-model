"""Optional module: coalitions inside dominant capital.

THE RULE IN PLAIN WORDS

Without this module dominant capital is one body. This module gives every firm a coalition
label and lets two coalitions inside dominant capital follow different routes.

  1. Labels. Every firm carries a label that it takes from its sector. The firms of some
     sectors carry the label of the conflict coalition. These sectors stand for oil and arms.
     The firms of some other sectors carry the label of the takeover coalition. These sectors
     stand for civilian technology and corporate takeovers. All other firms carry no label.
     A coalition, in the rule below, is the firms of the top hundred that carry its label.
  2. The danger zone. Each year the module compares the earnings per employee of the conflict
     coalition with the earnings per employee of the top hundred as a whole. While the
     coalition earns less than that average, it is in the danger zone, and a level of conflict
     rises. The level rises faster when the conflict coalition is the larger of the two
     coalitions, and more slowly when the takeover coalition is the larger. While the
     coalition earns the average or more, the level of conflict falls.
  3. Violence. The violence of a year is the level of conflict or the intensity of
     stagflation, whichever is higher, because the book says that every period of stagflation
     was "accompanied by heightened conflict and violence".
  4. What violence does for the conflict coalition. Its firms raise their prices by an extra
     amount in proportion to the violence. They give up some employees for each price rise.
     No other firm receives this rise. What a firm of the coalition earns per employee
     above the other firms of the top hundred is its war premium. In a year without
     violence the firm loses a fixed part of that premium. The coalition therefore drifts
     back toward the average in quiet years, and it can fall into the danger zone again.
  5. The spark. The level of conflict is passed to the stagflation module as a spark. The
     spark is scaled down while the top hundred hold little of the economy. The stagflation
     module then acts as if the intensity of stagflation were at least as high as the spark.
     The conflict coalition can therefore start a bout of stagflation that dominant capital
     as a whole did not start.
  6. What quiet does for the takeover coalition. In a year without violence the firms of the
     takeover coalition seek to buy more than other buyers do. The advantage shrinks in
     proportion to the violence and is gone at full violence. The module passes this to the
     merger module as a number for each sector.
  7. Readouts. The module publishes each label's part of all capitalization, which is the
     measure of Figure 17.3, and each coalition's part of the capitalization of the top
     hundred, which is the measure of Figure 5.9 in the 2002 book.

The module never moves earnings from one coalition to the other. A coalition gains at the
other's expense in the differential sense of the theory: its part of the total rises and the
other's part falls.

WHAT IT RESTS ON

  - Capital as Power, chapter 17, "Coalitions". The history of differential accumulation
    "depends crucially on what happens within dominant capital. This process includes the
    inner conflicts between various corporate-state coalitions and alliances that comprise
    the nuclei of dominant capital". "During the depth phase of the 1970s and 1980s,
    differential accumulation was led by a 'Weapondollar-Petrodollar Coalition' made up of
    large oil companies, armament contractors and OPEC". "The Weapondollar-Petrodollar
    Coalition, however, thrived, while the other members of dominant capital - although hit by
    the stagnation - ended up benefiting greatly from the consequent inflation". The challenge
    came from "a new 'Technodollar-Mergerdollar Alliance', a group based on civilian high-tech
    and corporate takeovers". Figure 17.3 measures each group's "share of global market
    capitalization": the oil and arms firms held "nearly 14 per cent" in 1981 and "a meagre
    4 per cent" in 2000, when the other alliance held 20 per cent. The chapter says that an
    analysis of the coalitions "is beyond the scope of this volume".
  - The same chapter, "The role of the Middle East": the depth regime of the 1970s "was
    accompanied by heightened conflict and violence", with "military conflict, especially in
    the Middle East, contributing to rising energy prices, and therefore to higher
    inflation". Part 3 rests on this.
  - The postscript of chapter 17. When mergers receded after 2000 and inflation fell, "it was
    the brinkmanship of the Weapondollar-Petrodollar Coalition that saved the day. The
    coalition managed to put the Bush clan back in the White House, inflame the Middle East,
    raise the price of oil and provide the necessary spark for inflation". Part 5 rests on this.
  - Nitzan and Bichler, "Bringing Capital Accumulation Back In" (1995), section 5. "As long as
    the Petro-Core's rate of return exceeds the big economy's average, the oil companies'
    performance will appear satisfactory or even superior, leading to a moderate stance on
    Middle Eastern affairs. When their performance falls below the 'normal', however, we enter
    the so-called 'danger zone': for the Petro-Core, the status quo of non-violent tension is
    no longer sufficient and open hostilities become increasingly appealing." The paper
    reports three regularities for 1966 to 1991: "every 'danger zone' was followed by an
    outbreak of Middle East 'energy conflict'"; after each conflict "the Petro-Core's rate of
    return moved to surpass or at least match the Fortune 500 average"; and "no 'energy
    conflict' erupted without the Petro-Core first falling into a 'danger zone'". Part 2 is
    this hypothesis. Section 4 of the paper describes the price: the onset of a war "generated
    a crisis atmosphere which was sufficient to create a fear of shortage and cause prices to
    rise", and with "the diffusion of a 'crisis' - either at the end of a war, or when it
    became clear that its continuation posed no danger to the flow of oil - the price began
    to stagnate or fall". The industry's price consensus includes "in addition to its
    'peacetime' basis, also such items as 'embargo effects' and 'war premiums'". The paper
    adds that "the precise magnitude of such premiums cannot be easily determined". The rise
    and the fading of the premium in part 4 rest on this.
  - Nitzan and Bichler, The Global Political Economy of Israel (2002), chapter 5. The oil
    companies were content "as long as they accumulated differentially relative to dominant
    capital as a whole". For them hostilities "were beneficial only up to a point", because
    "excessively high oil prices tended to encourage energy substitution, weaken profits in
    downstream operations, and lure entry from potential competitors". The loss of employees
    in part 4 rests on this. The mechanism "was by no means eternal. Indeed, after the 1990/91
    Gulf War, a new 'danger zone' opened up - and yet this time there was no 'energy conflict'
    to close it". The reason given is a shift inside dominant capital: "from the viewpoint of
    dominant capital as a whole, that route was unattractive, and in fact dangerous. By the
    early 1990s, civilian business offered much better ways to beat the average. Furthermore,
    the new civilian avenues required relative openness and stability, the very opposite of
    the conflict and stagflation with which the Weapondollar-Petrodollar Coalition fuelled the
    earlier depth regime." The coalition "has lost its earlier primacy". The slower rise of
    conflict when the takeover coalition is the larger, and part 6, rest on these sentences.
    Figure 5.9 of that chapter measures the two groups as parts of the capitalization of the
    Standard and Poor's 500.
  - The same book, chapter 6, "The Technodollar-Mergerdollar Coalition". "Whereas the
    earlier, depth-oriented Weapondollar-Petrodollar Coalition thrived on military conflict
    and inflation, the interest of the new alliance lay in civilian 'high-tech' and the
    'natural right to buy' anything vendible. The differential prosperity of this new
    coalition rested on three breadth-related poles": capital decontrols, privatisation and
    expansion into emerging markets. Part 6 rests on this.

WHAT IS ADDED

The literature gives the hypothesis of the danger zone, the direction of every effect and no
rates. Every number below is an addition. The literature names oil, arms and civilian
technology. The ledger has sectors with numbers and no names, so the choice of sectors is an
addition, and the two coalitions start with the same number of sectors so that neither starts
ahead. The papers compare rates of return on equity. The ledger has no equity on the books,
so the rule compares earnings per employee, which is the book's measure of depth. Measuring
which coalition has primacy by its part of the top hundred's capitalization is an addition.
Reckoning the war premium against the other firms of the top hundred is an addition, and it
treats any advantage of the coalition over those firms as a premium that fades.
Scaling the spark by the top hundred's part of all employees is an addition copied from the
compass, which limits the intensity of stagflation in the same way. The extra appetite of the
takeover coalition for acquisitions is an addition in its form: the literature says that this
coalition was "based on" takeovers and gives no measure.

WHAT IS MISSING

OPEC, the arms-importing governments and the governments that backed each coalition are not
in the ledger. The cycle of oil income and arms imports is not modelled. The book says that
high technology was "firing up both investor's hype and the stock market"; hype is held at
one in this model, so the takeover coalition gains only through buying. The takeover
coalition does not press for the opening of boundaries here, although the 2002 book names
capital decontrols as its first pole. The module publishes the numbers that a module for
boundaries or for organised force would need in order to read the coalitions.
"""
import numpy as np
from core import Scale, ScaleComponent, Publish, top_positions

PREMIUM = "war premium"    # this module's markup component; it stacks

NONE, CONFLICT, TAKEOVER = 0, 1, 2
UNSET = -1          # a firm founded after the start; it takes the label of its sector


class Coalitions:
    name = "coalitions"
    reads = ("concentration",)
    supplies = ("conflict", "conflict_spark", "merger_appetite", "danger_zone",
                "coalition_conflict_share", "coalition_takeover_share",
                "coalition_conflict_top", "coalition_takeover_top")
    figures = {                   # what the workbench calls each published number: label, unit, note
        "conflict": ("Level of conflict", "index", "Rises while the oil and arms coalition earns less per employee than the top 100."),
        "conflict_spark": ("Spark from conflict", "index", "The level of conflict passed to the stagflation module."),
        'danger_zone': ('Danger zone', 'share', "How far the oil and arms coalition's earnings per employee fall below the top 100's."),
        'coalition_conflict_share': ("Oil and arms coalition's share of capitalization", 'share', 'Its part of all capitalization.'),
        'coalition_takeover_share': ("Technology and takeover coalition's share of capitalization", 'share', 'Its part of all capitalization.'),
        'coalition_conflict_top': ("Oil and arms coalition's share of the top 100", 'share', "Its part of the top 100's capitalization."),
        'coalition_takeover_top': ("Technology and takeover coalition's share of the top 100", 'share', "Its part of the top 100's capitalization."),
    }

    def __init__(self, conflict_sectors=(0, 1), takeover_sectors=(2, 3), rise=0.5, fall=0.15,
                 price_rise=0.06, fade=0.2, volume_cost=0.5, spark=0.5, concert=4.0, takeover_edge=0.5, top=100):
        self.conflict_sectors = conflict_sectors    # sectors whose firms carry the label of the conflict coalition (stand-ins for oil and arms)
        self.takeover_sectors = takeover_sectors    # sectors whose firms carry the label of the takeover coalition (stand-ins for technology)
        self.rise = rise                # yearly rise in the level of conflict in the danger zone, when the conflict coalition is the only coalition
        self.fall = fall                # yearly fall in the level of conflict outside the danger zone
        self.price_rise = price_rise    # extra yearly price rise of the conflict coalition's firms at full violence
        self.fade = fade                # part of a firm's war premium that is lost in a year without violence
        self.volume_cost = volume_cost  # employees given up per unit of that price rise (the same figure as in the sabotage module)
        self.spark = spark              # part of the level of conflict that reaches the stagflation module when the top hundred hold much
        self.concert = concert          # the spark is complete when the top hundred hold one part in this many of all employees (as in the compass)
        self.takeover_edge = takeover_edge   # extra buying sought by the takeover coalition in a year without violence (0.5 means half as much again)
        self.top = top
        self.conflict = 0.0             # the level of conflict, from 0 to 1

    def sector_labels(self, L):
        lab = np.full(int(L.sector_of.max()) + 1, NONE)
        lab[list(self.conflict_sectors)] = CONFLICT
        lab[list(self.takeover_sectors)] = TAKEOVER
        return lab

    def labels(self, L):
        """The coalition label of every firm."""
        lab = L.extra["coalition"]
        return np.where(lab == UNSET, self.sector_labels(L)[L.sector], lab)

    def appetite(self, L, violence):
        a = np.ones(int(L.sector_of.max()) + 1)
        a[list(self.takeover_sectors)] = 1.0 + self.takeover_edge * (1.0 - violence)
        return a

    def measure(self, L):
        K, E, n = L.cap(), L.earnings(), L.n
        lab = self.labels(L)
        top = top_positions(K, np.arange(len(L)), self.top)
        out = {"lab": lab, "top": top}
        for key, code in ("conflict", CONFLICT), ("takeover", TAKEOVER):
            out[key + "_share"] = float(K[lab == code].sum() / K.sum())
            out[key + "_top"] = float(K[top][lab[top] == code].sum() / K[top].sum())
        mine = top[lab[top] == CONFLICT]
        out["members"] = mine
        # earnings per employee of the conflict coalition against that of the top hundred as a whole
        out["ratio"] = float((E[mine].sum() / n[mine].sum()) / (E[top].sum() / n[top].sum())) if mine.size else 1.0
        return out

    def start(self, L):
        L.add_attribute("coalition", self.sector_labels(L)[L.sector], UNSET)
        L.add_component(PREMIUM, self.name)      # the war premium: this module's markup component; it stacks
        m = self.measure(L)
        return {"conflict": 0.0, "conflict_spark": 0.0, "danger_zone": 0.0,
                "merger_appetite": self.appetite(L, 0.0),
                "coalition_conflict_share": m["conflict_share"], "coalition_takeover_share": m["takeover_share"],
                "coalition_conflict_top": m["conflict_top"], "coalition_takeover_top": m["takeover_top"]}

    def propose(self, L, rng):
        A = L.accounts
        m = self.measure(L)
        both = m["conflict_top"] + m["takeover_top"]
        primacy = m["conflict_top"] / both if both > 0 else 0.0      # 1 when the conflict coalition is the only coalition
        danger = m["members"].size > 0 and m["ratio"] < 1.0 - 1e-9   # earning less than dominant capital as a whole
        if danger:
            self.conflict = min(1.0, self.conflict + self.rise * primacy)
        else:
            self.conflict = max(0.0, self.conflict - self.fall)
        violence = float(np.clip(max(self.conflict, A.get("stagflation_intensity", 0.0)), 0.0, 1.0))
        spark = self.spark * self.conflict * min(1.0, self.concert * A["concentration"])

        changes = [Publish("conflict", self.conflict, self.name),
                   Publish("conflict_spark", spark, self.name),
                   Publish("danger_zone", 1.0 - m["ratio"] if danger else 0.0, self.name),
                   Publish("merger_appetite", self.appetite(L, violence), self.name),
                   Publish("coalition_conflict_share", m["conflict_share"], self.name),
                   Publish("coalition_takeover_share", m["takeover_share"], self.name),
                   Publish("coalition_conflict_top", m["conflict_top"], self.name),
                   Publish("coalition_takeover_top", m["takeover_top"], self.name)]
        r = self.price_rise * violence
        if m["members"].size:
            mine = np.zeros(len(L), dtype=bool)
            mine[m["members"]] = True
            markup = L.markup()
            # The war premium: what a coalition firm's markup holds above the markup of the
            # other firms of the top hundred. It fades in a year without violence.
            rest = m["top"][~mine[m["top"]]]
            usual = (L.n[rest] * markup[rest]).sum() / L.n[rest].sum() if rest.size else np.inf
            premium = np.where(mine, np.maximum(markup - usual, 0.0), 0.0)
            new = (1 + markup - self.fade * (1 - violence) * premium) * (1 + r) - 1   # the price rises and the wage does not
            new = np.where(mine, new, markup)
            changes += [ScaleComponent(PREMIUM, new / markup, self.name),   # the change is made to this module's own component; the price follows
                        Scale("employees", np.where(mine, 1 - self.volume_cost * r, 1.0), self.name)]
        return changes

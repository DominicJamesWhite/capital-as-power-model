"""Optional module: the normal rate of return following employment.

THE RULE IN PLAIN WORDS

In the main modules the normal rate of return is one fixed number. This module moves it. The
module is a rule for the conduct of government organs, which the book treats as bodies of the
same mode of power as corporations. Nothing in the rule comes from outside the model. The
growth of employment comes from the hiring that the other modules produce, and the change of
conduct in part 2 is produced by popular resistance.

  1. The customary rate. The normal rate of return that the ledger holds at the start of a
     run is taken as the customary rate. While part 2 has not happened the module leaves the
     rate alone.
  2. The change of conduct. In the first year in which popular resistance stands above a set
     level, government organs take up the practice of leaning against the growth of
     employment. The practice is never given up afterwards. Its force grows in equal yearly
     steps and is complete after twenty years.
  3. The rate follows employment. Each year the module takes the yearly growth of employment
     averaged over ten years, as that average stood five years earlier. It subtracts the
     growth of the working population. The normal rate of return is the customary rate plus
     that difference, times a setting called the slope, times the force of the practice. The
     slope says how many points the rate moves for each point of employment growth. Slower
     growth of employment is therefore followed, five years later, by a lower normal rate of
     return, and faster growth by a higher one. The rate is kept between a lowest and a
     highest level.
  4. The rate bears on hiring. The sabotage module has a markup at which small firms neither
     expand nor cut back. The module publishes a number that multiplies that markup. The
     number is 1 at the customary rate. It rises above 1 by a set part of the proportion by
     which the normal rate of return stands above the customary rate, and it falls below 1 in
     the same way. A higher rate therefore makes small firms hire less, and a lower rate
     makes them hire more. This is the only change to an existing module, and the number is 1
     when this module is off.
  5. Readouts. The module publishes the rate, the force of the practice, the lagged growth of
     employment that the rate follows, the number of part 4, the power index (the average
     capitalization of the hundred largest firms divided by the wage), and the same power
     index reckoned at the customary rate.

The module changes the ledger only by setting the shared number "nrr". Every firm's
capitalization is divided by the same normal rate of return, so the change raises or lowers
all capitalization in one proportion. Differential capitalization is a ratio of two
capitalizations and is not changed by part 3. Only part 4 can reach the differential measures.

WHAT IT RESTS ON

  - Capital as Power, chapter 12, "The normal rate of return and the natural rate of
    unemployment". "The normal rate of return of course is a fuzzy magnitude, a convention
    that varies among business owners and over time." The book speaks of "the ever-fluctuating
    capitalist normal rate of return". "Government deliberations and decisions are constantly
    under the long shadow of the bond market, and even central bankers, who ostensibly
    'determine' the short-term 'risk-free' rate of interest, in fact take their cue from the
    'market'." The aggregate consequence of differential sabotage is "a natural rate of
    unemployment on the one hand and a corresponding normal rate of return on the other".
    Part 1 rests on the word "convention", and part 3 on the pairing of the two rates.
  - Chapter 12, "Business as usual". The owner of a firm is told: "produce only if you expect
    to earn at least the normal rate of return. Otherwise, shut down." "This unwillingness to
    produce for less than some conventional rate of return is the very manifestation of
    industrial sabotage." Control is exercised "by making industrial activity conditional on
    earning a normal rate of return". Part 4 rests on these sentences.
  - Chapter 13, "Government capitalized". "The government bond market has become the heart of
    modern finance. It provides the biggest and most liquid security market; it offers a
    vehicle for both fiscal and monetary policy; and it reflects, through its benchmark yield,
    the universal normal rate of return." The module therefore treats the yield on government
    bonds and the normal rate of return as one number.
  - Chapter 14. "The normal rate of return is common to dominant capital and the average and
    therefore drops from the ratio."
  - Bichler and Nitzan, "A CasP Model of the Stock Market" (2016), sections 7.2 to 7.5 and 8,
    Figures 11 and 12. "From a power perspective, employment growth is an inverse proxy of
    strategic sabotage." "Until the middle of the twentieth century, there was little or no
    connection between the two series (Pearson coefficient of -0.12). But from the early 1960s
    onward, employment growth has been a nearly perfect five-year leading predictor for
    interest rates: the lower the rate of growth of employment (and therefore the greater the
    strategic sabotage), the lower the subsequent rate of interest (with a Pearson correlation
    of +0.89). And since lower interest rates boost capitalization, you can clearly see how
    strategic sabotage worked to fuel capitalized power." Part 3 is this relation. On the
    change of conduct: the bear market of the 1930s "was ultimately resolved by creordering
    the entire mode of power. The chief hallmark of this creordering was the rise of the
    Keynesian welfare-warfare state. And one of the key pillars of Keynesianism was
    discretionary countercyclical economic policy". "After 1939, though, capitalists started
    to expect government policy to mitigate the cycle"; "they expected higher employment
    growth to bring about tighter money, higher interest rates and therefore lower
    capitalization. This expectation took a bit to materialize, but as Figure 12 shows,
    eventually it became self-fulfilling." Part 2 rests on this. On the place of government:
    "the government is not some sort of exogenous distortion or an external alley but an
    integral component of the capitalization of power and the regulation of strategic
    sabotage". On hiring: "The consequence of tighter policy may be lower employment growth
    and lower profit here and now". The conclusion names "a CasP policy cycle - the idea that
    government policy, insofar as it caters to the imperative of capitalized power, favours
    low employment growth in order to enable low rates of interest", and says that lower
    growth of employment "enabled looser monetary policy and lower interest rates, thus
    helping to reduce the normal rate of return".

WHAT IS ADDED

The literature gives a correlation, a lead of five years and averages of ten years. It gives
no rule and no slope.
  - The lag of five years and the average of ten years are the paper's (Figure 12).
  - The direction of the slope is the paper's: "the lower the rate of growth of employment
    (and therefore the greater the strategic sabotage), the lower the subsequent rate of
    interest". The size of the slope has no source. The book and the 2016 paper give no
    figure for how far the rate moves, and they describe no relation from which the model
    could work one out. The slope is therefore a plain setting. Its default is 1, which means
    one point of the rate for one point of employment growth. The value 1 was chosen only
    because it is the simplest one, and it makes no claim about any country or period.
    No setting of the model is fitted to the historical record.
  - The twenty years of part 2 are the distance from 1939 to "the early 1960s". The equal
    yearly steps are an addition.
  - The paper says the mode of power was re-ordered after the crisis of the 1930s. It does
    not say what brings such a re-ordering about. Tying it to popular resistance, and the
    level of 0.3, are additions. That the practice is never given up is an addition.
  - Measuring the growth of employment against the growth of the working population is an
    addition. The paper does not say against what the growth of employment is measured.
  - Taking the starting rate as the customary rate is an addition.
  - The lowest rate of 1 per cent and the highest of 20 per cent are plain settings with no
    source. They exist because capitalization is divided by the rate, so the rate must stay
    above zero.
  - The form of part 4 and its strength of one quarter are additions. The book says that
    activity is conditional on the normal rate of return, and the paper says that tighter
    policy may lower employment growth. Neither gives a rule.
  - Before the change of conduct the module holds the rate fixed. The paper reports "little
    or no connection" in that period, and the book calls the rate "ever-fluctuating", so a
    fixed rate is a simplification.

WHAT IS MISSING

Inflation does not move the rate here, although chapter 16 says that the normal rate of
return is among the things "affected by inflation", and the high yields of the 1970s and
1980s came with inflation. The module has one rate, where chapter 13 says that each type of
instrument had "its own 'benchmark' and 'normal rate of return'". The bond market does not
appear as a set of holders who push the rate; the rule states the outcome and not the
contest. The paper's finding that the power index moved with employment growth before 1939
and against it afterwards is an outcome to look for and is not built in. The paper's link
from sabotage to systemic fear is not in this module. The debt module reckons the
government's debt as a fixed interest payment divided by the normal rate of return, so a
lower rate enlarges that debt without changing the interest paid on it.
"""
import numpy as np
from core import Set, Publish, top_positions


class PolicyRate:
    name = "policy_rate"
    reads = ("resistance",)
    supplies = ("policy_rate", "policy_rate_force", "policy_rate_employment_growth",
                "policy_rate_markup", "policy_rate_power_index", "policy_rate_power_index_customary")
    figures = {                   # what the workbench calls each published number: label, unit, note
        "policy_rate": ("Policy rate", "rate", ""),
        "policy_rate_force": ("Force of the practice", "index", ""),
        "policy_rate_employment_growth": ("Lagged growth of employment", "rate", "The growth of employment that the rate follows."),
        "policy_rate_markup": ("Markup factor from the rate", "times", "Multiplies the markup."),
        "policy_rate_power_index": ("Power index", "times", "Average capitalization of the top 100 divided by the wage."),
        "policy_rate_power_index_customary": ("Power index at the customary rate", "times", "Average capitalization of the top 100 divided by the wage, reckoned at the customary rate."),
    }

    def __init__(self, slope=1.0, lag=5, window=10, established_at=0.3, materialize=20,
                 hiring=0.25, lowest=0.01, highest=0.20, top=100):
        self.slope = slope                    # points of the normal rate of return per point of employment growth. A plain setting with no source: the 2016 paper gives the direction and no size. The default of 1 is the simplest value and is taken from no record
        self.lag = lag                        # years by which the rate follows employment growth (2016 paper, Figure 12: five)
        self.window = window                  # years over which employment growth is averaged (2016 paper, Figure 12: ten)
        self.established_at = established_at  # level of popular resistance at which government organs take up the practice (addition)
        self.materialize = materialize        # years from the change of conduct until the practice has its full force. The value is an addition: twenty years is the distance from 1939 to the early 1960s in the 2016 paper's account of the United States, which is one episode, and the paper gives no general length
        self.hiring = hiring                  # proportional change in the markup at which small firms neither expand nor cut back, per unit of proportional change in the rate (addition)
        self.lowest = lowest                  # the normal rate of return cannot fall below this (a plain setting with no source)
        self.highest = highest                # the normal rate of return cannot rise above this (a plain setting with no source)
        self.top = top
        self.customary = None                 # the rate in the ledger at the start of the run
        self.force = 0.0                      # 0 before the change of conduct, 1 when the practice is complete
        self.established = False
        self.last_employment = None
        self.growth = []                      # yearly growth of employment, oldest first

    def power_index(self, L, nrr):
        K = L.cap() * L.shared["nrr"] / nrr
        return float(K[top_positions(K, np.arange(len(L)), self.top)].mean() / L.shared["wage"])

    def start(self, L):
        self.customary = L.shared["nrr"]
        index = self.power_index(L, self.customary)
        return {"policy_rate": self.customary, "policy_rate_force": 0.0,
                "policy_rate_employment_growth": L.shared["workforce_growth"], "policy_rate_markup": 1.0,
                "policy_rate_power_index": index, "policy_rate_power_index_customary": index}

    def propose(self, L, rng):
        A = L.accounts
        employment = float(L.n.sum())
        if self.last_employment is not None:
            self.growth.append(employment / self.last_employment - 1.0)
        self.last_employment = employment
        self.growth = self.growth[-(self.lag + self.window):]

        # part 2: the change of conduct, brought about by popular resistance
        if not self.established and A["resistance"] > self.established_at:
            self.established = True
        if self.established:
            self.force = min(1.0, self.force + 1.0 / self.materialize)

        # part 3: the rate follows the growth of employment of five years earlier
        usual = L.shared["workforce_growth"]
        past = self.growth[:-self.lag] if self.lag else self.growth
        lagged = float(np.mean(past)) if past else usual
        rate = float(np.clip(self.customary + self.slope * self.force * (lagged - usual),
                             self.lowest, self.highest))

        # part 4: activity is conditional on earning the normal rate of return
        markup = max(0.0, 1.0 + self.hiring * (rate / self.customary - 1.0))

        return [Set("nrr", rate, self.name),
                Publish("policy_rate", rate, self.name),
                Publish("policy_rate_force", self.force, self.name),
                Publish("policy_rate_employment_growth", lagged, self.name),
                Publish("policy_rate_markup", markup, self.name),
                Publish("policy_rate_power_index", self.power_index(L, L.shared["nrr"]), self.name),
                Publish("policy_rate_power_index_customary", self.power_index(L, self.customary), self.name)]

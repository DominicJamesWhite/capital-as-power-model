"""Optional module: proletarianization.

THE RULE IN PLAIN WORDS

In the nine modules the working population grows every year at a rate that is typed in as a
setting. This module produces that rate. It holds a second population: people who live outside
wage employment (on the land, in households, in other countries). Firms and government organs
draw those people into the working population when few hands are idle, and the drawing slows
as the outside population is used up. The ceiling on green-field growth is then a quantity
inside the model: the number of people who are left to be drawn.

  1. The outside population. The module keeps a count of people outside wage employment. They
     work for no firm, they are not in the ledger, and they are not part of the working
     population that the ledger counts. At the start of a run there is one such person for
     every person in the working population.
  2. Natural increase. Both populations grow each year by the same rate of natural increase.
     This rate is the one part of the growth of the working population that is still typed in.
  3. The drive. Each year the module compares unemployment with a level called the sufficient
     reserve. When unemployment is at or above that level, employers have idle hands enough,
     and nobody is drawn in. When unemployment is below it, the drive is one minus
     unemployment divided by the sufficient reserve. The drive is 1 when nobody is idle.
  4. The barrier. Popular resistance stalls the drawing. The barrier is twice the level of
     popular resistance and never more than 1.
  5. The drawing. The number of people planned to be drawn in during the following year is a
     fixed part of the outside population, times the drive, times one minus the barrier. The
     number falls as the outside population falls, whatever the drive.
  6. Falling back. When unemployment is above the sufficient reserve, a part of the people
     who are idle beyond that reserve is planned to leave the working population for the
     outside population in the following year. They can be drawn in again later.
  7. The rate. The module sets the growth rate of the working population for the following
     year to the natural increase, plus the planned drawing, minus the planned falling back,
     both as parts of the working population. The other modules read that rate exactly as
     they read the typed-in setting. In the first year of a run the typed-in rate is still in
     force, and the module counts the people it implies as drawn from the outside population.
  8. Loosening. The module publishes a number that the compass multiplies into the cohesion of
     dominant capital. The number is 1 divided by (1 plus a weight times the year's planned
     drawing as a part of the working population). It is 1 when nobody is being drawn in.
  9. Readouts. The module publishes the outside population as a part of all people, the
     drive, the barrier, the planned drawing and falling back as parts of the working
     population, and the growth rate it has set.

Nothing in the rule comes from outside except the natural increase. Unemployment comes from
the hiring and pricing of the other modules, and popular resistance from the resistance module.

WHAT IT RESTS ON

  - Capital as Power, chapter 14, Table 14.2, "External Breadth: Green-field Investment".
    "This method is labelled 'external' because, from a societal perspective, it involves a
    net addition of employees. Its upper ceiling is the extent of proletarianization." Parts
    1 and 5 rest on this: the ceiling is the count of people not yet in wage employment.
  - Nitzan and Bichler, "Going Global: Differential Accumulation and the Great U-turn in
    South Africa and Israel" (2001). External breadth "involves the redistribution of new
    demand, principally generated by population growth and by proletarianization", and it is
    "far more sustainable, particularly as long as significant portions of the population are
    yet to be proletarianized". Part 2 and part 5 keep the two sources apart, as this
    sentence does.
  - The same paper. "Having a large rural population does not guarantee proletarianization,
    which can stall for cultural or religious reasons." In South Africa "roughly half the
    population is still rural and yet to be proletarianized", and "for the time being, though,
    this potential is capped by lingering racial conflict, massive crime, growing corruption,
    and an AIDS epidemic". Part 4 rests on this: a large outside population is not enough,
    and conflict stalls the drawing.
  - The same paper. "Periods of rapid population growth and proletarianization tend to loosen
    the internal cohesiveness of corporate coalitions, making differential price increases
    both more difficult and less desirable (since they undermine market share). The situation
    changes markedly when population growth subsides or when proletarianization runs into
    barriers. When that happens, pricing power, as well as the benefit from deeper margins,
    tend to rise." And: "when proletarianization runs into barriers, the core groups
    gravitate, with a mixture of fear and greed, toward depth". Part 8 rests on this.
  - Bichler and Nitzan, The Global Political Economy of Israel (2002), chapter 2. "Green-field
    growth is tempting, particular in the presence of 'non-capitalist',
    'proletarianisation-ready' populations in and outside one's own society." The outside
    population of part 1 therefore includes people in other countries.
  - The same book, chapter 3, citing Farjoun. After 1967 "there was a growing need 'for a
    cheap, mobile labour force, with no social rights; a free labour force in the classical
    meaning of the term'. This was achieved by the proletarianisation of the Palestinian
    population, which was rapidly becoming the main labour pool". The same chapter: the annexation
    "was tantamount to a massive injection of breadth", and "by the mid-1970s, with the
    integration complete, growth again plummeted". Part 3 rests on the words "a growing
    need": the drawing answers the employers' want of hands. Part 5 rests on "with the
    integration complete": a pool that has been drawn in gives no more growth.
  - The same book, chapter 1, speaks of "the controlled proletarianisation of a rapidly
    growing immigrant population" among "the institutions of differential accumulation".
    Chapter 13 of Capital as Power treats corporations and government organs as bodies of one
    mode of power. The module therefore names no separate actor that does the drawing.
  - Capital as Power, chapter 17. "The postwar rebuilding of Europe and Japan ... in some
    sense was equivalent to the re-proletarianization of their societies. The result was a
    powerful breadth engine." Part 6 rests on this: people who were once in wage employment
    can be outside it again, and drawing them back in is a new source of breadth.
  - Bichler and Nitzan, "Dominant Capital and the New Wars" (2004). "Accumulation, which
    during the nineteenth century was anchored largely in proletarianization and technical
    advances, has come to depend more and more on corporate amalgamation and inflationary
    pricing." The drawing is therefore not tied to concentration: it is strongest at the
    start of a run, when dominant capital holds little. "A breadth regime relies on
    proletarianization, on green-field investment and, particularly, on mergers."
  - Bichler and Nitzan, "Regimes of Differential Accumulation" (2001), conclusion. "Half of
    the world's population still lives pretty much outside the capitalist fold. Their
    proletarianization promises plenty of new green-field investment to come." The starting
    figure of one outside person for each person in the working population borrows the word
    "half" from this sentence and from the sentence on South Africa.
  - Capital as Power, chapter 12. United States population growth "fell to 2.2 per cent
    between the Civil War and the turn of the twentieth century, and further down to 1.6 per
    cent between the turn of the century and the onset of the Great Depression". These are
    figures to compare the produced rate with. They are not settings.

WHAT IS ADDED

The literature says that the ceiling is the extent of proletarianization, that the drawing
answers a need for hands, that it can stall, that it loosens the cohesion of dominant capital
while it lasts, and that its end turns dominant capital toward depth. It gives no rule and no
rate. Every number below is an addition. The form of the drive in part 3 is an addition, and
so is the level called the sufficient reserve. Measuring the barrier by popular resistance is
an addition: the literature names cultural and religious reasons and racial conflict, and the
model has only one level of popular resistance. Part 6 is an addition in its form. The book's
case of re-proletarianization followed a war, and the rule lets heavy unemployment do what the
war did. The form and the weight of part 8 are additions. The starting figure borrows a
fraction that the literature gives for the world and for South Africa near the year 2000.

WHAT IS MISSING

The natural increase is still typed in. The literature calls the drawn-in labour "cheap" and
without "social rights", and the model has one wage, so the drawing does not weaken wages. The
literature describes confiscation of land, occupation and controlled immigration as the means,
and the rule has no such means: organised force helps only by wearing down popular resistance
in the resistance module. The outside population does not resist on its own account. The
outside population buys nothing and sells nothing, so the "new demand" of the 2001 paper
appears only as new hands. The model has one country, so people drawn from abroad and people
drawn from the land are not told apart.
"""
import numpy as np
from core import Set, Publish


class Proletarianization:
    name = "proletarianization"
    reads = ("unemployment",)
    supplies = ("outside_population", "proletarianization_drive", "proletarianization_barrier",
                "proletarianization_rate", "falling_back_rate", "workforce_growth_made", "breadth_cohesion")

    def __init__(self, start_outside=1.0, natural_increase=0.010, draw_rate=0.02, sufficient_reserve=0.08,
                 stall=2.0, falls_back=0.2, loosen=40.0):
        self.start_outside = start_outside            # people outside wage employment at the start, for each person in the working population (addition; "half" is borrowed from two sentences about the world and South Africa near 2000, which say nothing about the country or the starting year of a run)
        self.natural_increase = natural_increase      # yearly growth of both populations by births over deaths; the one part of growth still typed in (addition)
        self.draw_rate = draw_rate                    # part of the outside population drawn in during a year when nobody is idle and nothing stalls the drawing (addition)
        self.sufficient_reserve = sufficient_reserve  # unemployment at which employers have idle hands enough and draw nobody in (addition)
        self.stall = stall                            # part of the drawing stopped per unit of popular resistance (addition)
        self.falls_back = falls_back                  # part of the people idle beyond the sufficient reserve who leave the working population in a year (addition); 0 switches falling back off
        self.loosen = loosen                          # fall in the cohesion of dominant capital per unit of yearly drawing, measured as a part of the working population (addition); 0 switches the loosening off
        self.outside = 0.0                            # people outside wage employment, in the unit of employees
        self.first = 0.0                              # the outside population at the start, grown by natural increase: what it would be had nobody been drawn

    def start(self, L):
        self.outside = self.first = self.start_outside * L.shared["workforce"]          # part 1
        # The loosening starts at its neutral value, so that the order of the modules cannot matter.
        return {"outside_population": self.start_outside / (1 + self.start_outside),
                "proletarianization_drive": 0.0, "proletarianization_barrier": 0.0,
                "proletarianization_rate": 0.0, "falling_back_rate": 0.0,
                "workforce_growth_made": L.shared["workforce_growth"], "breadth_cohesion": 1.0}

    def propose(self, L, rng):
        A = L.accounts
        W, in_force, u = L.shared["workforce"], L.shared["workforce_growth"], A["unemployment"]
        b = self.natural_increase

        # Parts 2 and 7: the rate in force this year was set last year (in the first year it is the
        # typed-in rate). The green-field module adds in_force * W people this year. Those beyond
        # the natural increase come from the outside population, or return to it if the number is negative.
        moved = (in_force - b) * W
        self.outside = max(self.outside * (1 + b) - moved, 0.0)
        self.first *= 1 + b
        W_next = W * (1 + in_force)

        # Parts 3 to 6: the plan for next year.
        drive = float(np.clip(1 - u / self.sufficient_reserve, 0.0, 1.0))
        barrier = float(min(1.0, self.stall * max(0.0, A.get("resistance", 0.0))))
        draw = self.draw_rate * drive * (1 - barrier) * self.outside
        back = self.falls_back * max(0.0, u - self.sufficient_reserve) * W
        rate = b + (draw - back) / W_next                                             # part 7

        out = {"outside_population": self.outside / (self.outside + W_next),            # part 9
               "proletarianization_drive": drive,
               "proletarianization_barrier": barrier,
               "proletarianization_rate": draw / W_next,
               "falling_back_rate": back / W_next,
               "workforce_growth_made": rate,
               "breadth_cohesion": 1.0 / (1.0 + self.loosen * draw / W_next)}           # part 8
        return [Set("workforce_growth", float(rate), self.name)] + \
               [Publish(key, float(value), self.name) for key, value in out.items()]

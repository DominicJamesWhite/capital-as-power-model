"""Optional module: ownership of nature.

THE RULE IN PLAIN WORDS

A few industries stand for the industries that sell what is taken from nature, with oil as the
model case. The module holds no reserves, no output in barrels and no physical limit of any
kind. It holds only the cohesion of the owners of each of these industries, which is a number
between 0 and 1. The markup of a resource industry follows that number and nothing else.

  1. The resource industries. A setting names them. All firms in a named industry are owners
     of the resource, whatever their size, and a firm founded in the industry is an owner too.
  2. Tight ownership. Each year the module measures, for each resource industry, the part of
     the industry's employees that its seven largest firms hold. This part is the tightness
     of ownership. It rises when firms of the industry are bought up, and it falls when new
     firms enter the industry.
  3. The atmosphere of crisis. The module reads the violence of the year. The violence is the
     intensity of stagflation, or the level of conflict of the coalitions module, or the level
     of organised force, whichever is highest. Dominant capital produces all three, and none
     comes from outside. When the violence rises from one year to the next, an atmosphere of
     crisis rises by the same amount. Every year the atmosphere loses a fixed part of itself,
     whether the violence has ended or goes on. A crisis that continues without getting worse
     therefore stops frightening buyers and stops uniting sellers.
  4. Cohesion. The cohesion of the owners of a resource industry is the tightness of ownership,
     plus the atmosphere of crisis applied to the part that tight ownership leaves open. Few
     owners can act together without a crisis. Many owners can act together only while a
     crisis lasts.
  5. The markup. With no cohesion the industry sells at the free-flow markup, which is the
     normal markup of the sabotage module. With full cohesion it sells at the limited-flow
     markup, at which its price is a fixed multiple of the free-flow price. The markup the
     owners aim at lies between the two in proportion to their cohesion. Each year the markup
     of the industry closes a fixed part of the gap to that aim. Every firm of the industry
     receives the same proportional change. The price moves with the markup and the wage does
     not. No quantity of the resource appears anywhere in this part.
  6. Restriction. In a year when the markup rises, every firm of the industry gives up
     employees in proportion to the rise of its price. The owners limit the flow. Nature does
     not.
  7. Entry. Ownership keeps others out. The module publishes, for each industry, the part that
     is open to newcomers. It is one minus the cohesion in a resource industry, and 1 in every
     other industry. The green-field module founds fewer new firms in proportion, and the
     sabotage module allows less of the extra hiring that a high markup would otherwise bring.
     When cohesion breaks, the high markup draws a rush of newcomers, and the sabotage module's
     own rule for undercutting wears the markup down.
  8. Readouts, published every year and measured at the start of the year:
       nature_cohesion               average cohesion of the owners of the resource industries
       nature_tightness              average tightness of ownership (part 2)
       nature_atmosphere             the atmosphere of crisis (part 3)
       nature_markup                 markup of the resource industries taken together
       nature_relative_price         their price divided by the price level of all firms
       nature_differential_earnings  their earnings per employee divided by that of all firms
       nature_share                  their part of all capitalization
       nature_top                    their firms' part of the capitalization of the top hundred
       nature_open                   the number of part 7, one for each industry

The module does not start any crisis. It turns a crisis that dominant capital has produced into
a higher price for the owners of nature. If the coalitions module is on, the owners of oil can
also produce the crisis themselves, because that module raises its level of conflict when its
conflict coalition earns less than the top hundred.

WHAT IT RESTS ON

  - Capital as Power, chapter 16, the footnote on "peak commodities". "Mother Nature does
    impose real limits, but natural limits do not determine prices. Ownership does. Recall
    that price implies restriction, and restriction presupposes ownership. This prerequisite
    means that natural limits can have no bearing on prices unless they are mediated through
    the power conferred by ownership. The ozone layer, clean water and ocean fish stocks, to
    name a few obvious examples, are as physically limited as oil is. Yet having no owners to
    restrict their use and therefore no prices, they cannot be made 'scarce'. By contrast, oil
    is tightly owned, mostly by governments of oil-producing countries and large petroleum
    companies. And it is the historical variations in the relative power of these owners -
    exercised mostly through the high politics of crisis and war - that explains why the price
    of oil varies so dramatically while its actual 'availability' does not". "Note that even
    when oil finally becomes nearly exhausted, there will be nothing to prevent its owners
    from giving it away for free if they so wished." Parts 5 and 7 rest on this, and so does
    the absence of any physical quantity.
  - The same chapter, "The stagflation norm". Crises "enable a consensus to emerge within
    dominant capital", and "'peak commodities' in the late 2000s" is in its list of
    "inflation-triggering crises". Part 3 rests on this.
  - Nitzan and Bichler, "Bringing Capital Accumulation Back In" (1995), section 4.
    In the "free-flow" era "the
    international petroleum arena was all but completely dominated by the large companies",
    the "Seven Sisters". Later "the growing number of independent producers exerted downward
    pressure on prices". "The relentless search for new reserves and the incessant
    proliferation of technology created a constant menace of excess capacity and falling
    prices. With a growing number of actors, counteracting this threat solely via corporate
    collusion became increasingly difficult". Parts 2 and 7 rest on this.
  - The same paper, section 5, "Scarcity, anxiety and the price of oil". The ratio of proven
    reserves to production "rose by a quarter" while "the real price of crude oil was three to
    four times higher than what it was in the 1960s", "an increase which must hence be
    ascribed to institutional factors". The chart of inventories "does not betray any
    systematic relationship between 'scarcity' and price movement". The number of players
    grew "from less than a dozen in the 1960s, to over 150 by the late 1970s", and yet
    "collective action was in fact more effective with hundreds of participants during the
    1970s and 1980s, than with only a handful before the onset of the crisis", because the
    price depends "also on the nature of perceived scarcity associated with 'external'
    circumstances". Militarization "helped maintain prices even in the absence of tight
    producer coordination". "Despite the absence of any real shortage, the onset of these wars
    generated a crisis atmosphere which was sufficient to create a fear of shortage and cause
    prices to rise. Similarly, the diffusion of a 'crisis' - either at the end of a war, or
    when it became clear that its continuation posed no danger to the flow of oil - the price
    began to stagnate or fall." Parts 3 and 4 are these sentences. The multiple of part 5 is
    the "three to four times" of this section.
  - Nitzan and Bichler, The Global Political Economy of Israel (2002), chapter 5.
    In the 1980s "the OPEC front was no longer
    united and two important members of the cartel were themselves military foes". "Rivalry
    prevailed instead of cooperation, and with no end in sight to the hostilities, the
    likelihood of restoring OPEC's earlier cohesion seemed remote." The war "forced both to
    stretch production to the limit, creating a gushing flow of 'distress oil'", so that "from
    a certain point onward, the Iran-Iraq War turned from a blessing to a curse". The fading
    of the atmosphere while the violence goes on rests on this. High prices also "induced
    greater energy efficiency, substitution to alternative sources, and further exploration
    and output by non-OPEC producers", and Saudi Arabia "had to reduce its output from 9.8
    million barrels a day in 1981, to 6.5 million in 1982 and, finally, to a mere 3.2 million
    in 1985" to hold the price. Parts 6 and 7 rest on this.
  - Bichler and Nitzan, "Still About Oil?" (2015), record 432 of the authors' archive.
    "The price of oil has
    little to do with the commodity's actual scarcity, however estimated. But it has plenty to
    do with its perceived scarcity." In the limited-flow regime the oil "was now fine-tuned by
    OPEC quotas to fit 'what the market can bear'", and "OPEC and the companies concentrated
    on raising oil prices to profit from the sabotage of inflation and stagnation they
    inflicted on the rest of the world". "In the oil sector, profits and incomes are 'all in
    the price'": the differential earnings per share of the integrated oil companies and the
    relative price of oil have a correlation of 0.83, and the figure for the whole oil and gas
    sector is "practically the same". Giving every firm of the industry the same change
    (part 5) and the two readouts of relative price and differential earnings rest on this.
    The energy conflict "serves not the end users of oil, but its owners, sellers and
    associated allies; and it does so not by cheapening oil, but by making it more expensive".

WHAT IS ADDED

The literature gives the direction of every part and one figure, the price multiple. It gives
no rule. These things are added:
  - The choice of industries. The ledger has industries with numbers and no names. The three
    named by default lie in sector 0, which the coalitions module gives to oil and arms.
  - Measuring tight ownership by the part of an industry's employees that its seven largest
    firms hold. Seven is the number of the Seven Sisters. The measure itself is an addition.
  - The form of part 4, in which crisis supplies the cohesion that tight ownership lacks. The
    1995 paper says both that a rapid rise needs "a tight institutional framework" and that
    crisis kept prices up without "tight producer coordination". The rule follows the second.
  - Making the atmosphere rise with the yearly rise in violence and fade at a fixed rate.
  - Using the "three to four times" of the late 1980s as the price at full cohesion. The
    1995 paper also reports an "eighteen-fold rise" of the money price from 1972 to 1982, so
    3.5 is a low reading.
  - The speed at which the markup closes the gap, the employees given up for a price rise
    (the figure of the sabotage module), and the linear form of parts 5 and 7.

WHAT IS MISSING

The governments of the producing countries, which the book names first among the owners of oil,
are not in the ledger, and neither is OPEC. The owners here are firms only. The cycle
in which oil income pays for arms imports is not modelled. The owners do not start a conflict in
this module. The "relative power of these owners" is measured only by their cohesion, and not by
their standing with government organs. The 2002 book says that high oil prices "weaken profits in
downstream operations"; the ledger has no purchases between firms, so no other firm pays more
for the resource and the stagflation module is not told of the price rise. The resistance module
is not told of it either. Things that have no owner, which the book says "cannot be made
'scarce'", have no firm in the ledger and so do not appear at all.
"""
import numpy as np
from core import Scale, ScaleComponent, Publish, top_positions

PREMIUM = "resource premium"    # this module's markup component; it stacks


class Nature:
    name = "nature"
    reads = ("stagflation_intensity",)
    supplies = ("nature_open", "nature_cohesion", "nature_tightness", "nature_atmosphere",
                "nature_markup", "nature_relative_price", "nature_differential_earnings",
                "nature_share", "nature_top")
    figures = {                   # what the workbench calls each published number: label, unit, note
        "nature_cohesion": ("Cohesion of resource owners", "index", "Average cohesion of the owners of resource industries."),
        "nature_tightness": ("Tightness of resource ownership", "index", ""),
        "nature_atmosphere": ("Atmosphere of crisis", "index", ""),
        "nature_markup": ("Markup of resource industries", "number", "Markup of the resource industries taken together."),
        "nature_relative_price": ("Relative price of resources", "times", "Their price divided by the price level of all firms."),
        "nature_differential_earnings": ("Differential earnings of resources", "times", "Their earnings per employee divided by that of all firms."),
        'nature_share': ("Resources' share of capitalization", 'share', 'Part of all capitalization.'),
        'nature_top': ("Resources' share of the top 100", 'share', "Part of the top 100's capitalization."),
    }

    def __init__(self, industries=(0, 20, 40), core_owners=7, free_flow_markup=0.10,
                 price_multiple=3.5, speed=0.25, alarm=1.0, diffusion=0.3, volume_cost=0.5,
                 keep=0.5, top=100):
        self.industries = tuple(industries)        # the industries that stand for resource industries; an addition (three industries of sector 0, the oil and arms sector of the coalitions module)
        self.core_owners = core_owners             # the number of largest firms whose part of the industry measures tight ownership; 7 for the "Seven Sisters" (1995 paper); the measure is an addition, and so is the number: seven is the count of one historical group of oil companies, and the paper does not give it as a measure of tight ownership
        self.free_flow_markup = free_flow_markup   # markup of a resource industry whose owners have no cohesion; the normal markup of the sabotage module; an addition
        self.price_multiple = price_multiple       # price at full cohesion as a multiple of the free-flow price. The value is an addition: "three to four times higher" (1995 paper, section 5) compares the real price of crude oil in the late 1980s and early 1990s with the 1960s, which is one observation, and the paper does not give it as the price that full cohesion brings
        self.speed = speed                         # part of the gap between the markup and the owners' aim that is closed in a year; an addition
        self.alarm = alarm                         # rise in the atmosphere of crisis per unit of yearly rise in violence; an addition
        self.diffusion = diffusion                 # part of the atmosphere of crisis that is lost each year; an addition
        self.volume_cost = volume_cost             # employees given up per unit of proportional price rise; the figure of the sabotage module; an addition
        self.keep = keep                           # smallest part of its employees a firm keeps in one year of restriction; an addition
        self.top = top                             # the number of largest firms that stands for dominant capital
        self.atmosphere = 0.0                      # the atmosphere of crisis, from 0 to 1
        self.last_violence = 0.0                   # the violence of the year before

    # ------------------------------------------------------------------ pieces of the rule

    def limited_flow_markup(self):
        """Part 5: the markup at which the price is the set multiple of the free-flow price."""
        return self.price_multiple * (1 + self.free_flow_markup) - 1

    def violence(self, L):
        """Part 3: the highest of the three kinds of violence that other modules publish."""
        A = L.accounts
        return float(np.clip(max(A.get("stagflation_intensity", 0.0), A.get("conflict", 0.0),
                                 A.get("force", 0.0)), 0.0, 1.0))

    def measure(self, L):
        """The state of each resource industry and the readouts, from the ledger as it stands."""
        A = L.accounts
        k = L.sector_of.size
        res = np.array([r for r in self.industries if r < k], dtype=int)
        wage = L.shared["wage"]
        n = np.bincount(L.ind, L.n, k)
        earnings = np.bincount(L.ind, L.n * (wage * L.priced_markup()), k)   # earnings from the markup as priced, as in the sabotage module
        markup = np.where(n > 0, earnings / (wage * np.maximum(n, 1e-12)), self.free_flow_markup)
        tight = np.zeros(k)
        for r in res:                                                     # part 2
            sizes = L.n[L.ind == r]
            if sizes.size:
                c = min(self.core_owners, sizes.size)
                tight[r] = np.partition(sizes, -c)[-c:].sum() / sizes.sum()
        cohesion = np.zeros(k)
        cohesion[res] = tight[res] + (1 - tight[res]) * self.atmosphere   # part 4
        owner = np.isin(L.ind, res)
        K, top = L.cap(), top_positions(L.cap(), np.arange(len(L)), self.top)
        has = owner.any()
        own_n = L.n[owner].sum() if has else 1.0
        out = {"res": res, "n": n, "markup": markup, "tight": tight, "cohesion": cohesion, "owner": owner}
        out["readouts"] = {
            "nature_cohesion": float(cohesion[res].mean()) if res.size else 0.0,
            "nature_tightness": float(tight[res].mean()) if res.size else 0.0,
            "nature_atmosphere": float(self.atmosphere),
            "nature_markup": float(L.markup_earnings()[owner].sum() / (wage * own_n)) if has else 0.0,
            "nature_relative_price": float((L.p[owner] * L.n[owner]).sum() / own_n
                                           / ((L.p * L.n).sum() / L.n.sum())) if has else 1.0,
            "nature_differential_earnings": float(L.earnings()[owner].sum() / own_n
                                                  / (L.earnings().sum() / L.n.sum())) if has else 1.0,
            "nature_share": float(K[owner].sum() / K.sum()),
            "nature_top": float(K[top][owner[top]].sum() / K[top].sum()),
            "nature_open": 1.0 - cohesion,                               # part 7
        }
        return out

    # ------------------------------------------------------------------ start and yearly step

    def start(self, L):
        L.add_component(PREMIUM, self.name)
        return self.measure(L)["readouts"]

    def propose(self, L, rng):
        # Part 3: the atmosphere of crisis rises with the onset of violence and diffuses every year.
        violence = self.violence(L)
        self.atmosphere = float(np.clip(self.atmosphere * (1 - self.diffusion)
                                        + self.alarm * max(0.0, violence - self.last_violence), 0.0, 1.0))
        self.last_violence = violence

        m = self.measure(L)
        changes = [Publish(key, value, self.name) for key, value in m["readouts"].items()]
        res = m["res"][m["n"][m["res"]] > 0]
        if res.size == 0:
            return changes

        # Part 5: the markup follows the cohesion of the owners.
        markup = m["markup"]
        aim = self.free_flow_markup + (self.limited_flow_markup() - self.free_flow_markup) * m["cohesion"]
        new = markup.copy()
        new[res] = markup[res] + self.speed * (aim[res] - markup[res])   # between the markup and the aim, both above nothing
        # Part 6: a price rise is paid for with restriction.
        price = (1 + new) / (1 + markup)
        limit = np.maximum(1 - self.volume_cost * np.maximum(price - 1, 0.0), self.keep)
        ind = L.ind
        # The move of the industry's markup toward the owners' aim is made to this module's own component.
        changes += [ScaleComponent(PREMIUM, (new / markup)[ind], self.name),   # the price follows: the core works it out
                    Scale("employees", limit[ind], self.name)]
        return changes
